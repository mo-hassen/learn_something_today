/// Pumps the whole app on fast in-memory repositories. Extra [overrides]
/// win over the defaults because they come later in the list.
Future<void> pumpApp(
  WidgetTester tester, {
  String initialLocation = Routes.home,
  ArticlesRepository? articles,
  AiRepository? ai,
  AuthRepository? auth,
  FavouritesRepository? favourites,
  SettingsRepository? settings,
  DateTime? now,
  Size size = const Size(800, 1800),
  bool settle = true,
}) async {
  tester.view
    ..physicalSize = size
    ..devicePixelRatio = 1;
  addTearDown(tester.view.reset);
  await tester.pumpWidget(
    ProviderScope(
      // Riverpod 3 refuses to override one provider twice, so each source
      // is a parameter with a fast in-memory default.
      overrides: <Override>[
        routerProvider.overrideWithValue(
          createRouter(initialLocation: initialLocation),
        ),
        articlesRepositoryProvider.overrideWithValue(
          articles ?? InMemoryArticlesRepository(delay: Duration.zero),
        ),
        authRepositoryProvider.overrideWithValue(
          auth ?? InMemoryAuthRepository(delay: Duration.zero),
        ),
        aiRepositoryProvider.overrideWithValue(
          ai ?? StubAiRepository(delay: Duration.zero),
        ),
        nowProvider.overrideWithValue(now ?? testClock),
        if (favourites != null)
          favouritesRepositoryProvider.overrideWithValue(favourites),
        if (settings != null)
          settingsRepositoryProvider.overrideWithValue(settings),
      ],
      retry: (retryCount, error) => null, // no automatic retries in tests
      child: const LearnSomethingTodayApp(),
    ),
  );
  if (settle) {
    await tester.pumpAndSettle();
  } else {
    await tester.pump();
  }
}

/// Taps a tab of the bottom navigation bar by its label.
Future<void> tapTab(WidgetTester tester, String label) async {
  await tester.tap(
    find.descendant(of: find.byType(NavigationBar), matching: find.text(label)),
  );
  await tester.pumpAndSettle();
}

/// The container behind the running app, to read or change state directly.
ProviderContainer containerOf(WidgetTester tester) {
  return ProviderScope.containerOf(tester.element(find.byType(MaterialApp)));
}
