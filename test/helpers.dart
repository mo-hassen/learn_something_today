/// An articles source that can be switched between failing and working,
/// to test the error state and the retry button.
class FlakyArticlesRepository implements ArticlesRepository {
  FlakyArticlesRepository({this.failing = true})
    : _working = InMemoryArticlesRepository(delay: Duration.zero);

  bool failing;
  final InMemoryArticlesRepository _working;

  T _guard<T>(T Function() action) {
    if (failing) throw const NetworkException('The network is down.');
    return action();
  }

  @override
  Future<Article> featuredArticle(DateTime date, ArticleLanguage language) {
    return Future(() => _guard(() => _working.featuredArticle(date, language)));
  }

  @override
  Future<List<OnThisDayFact>> onThisDay(
    DateTime date,
    ArticleLanguage language,
  ) {
    return Future(() => _guard(() => _working.onThisDay(date, language)));
  }

  @override
  Future<Article> article(String id, ArticleLanguage language) {
    return Future(() => _guard(() => _working.article(id, language)));
  }

  @override
  Future<List<Article>> search(String query, ArticleLanguage language) {
    return Future(() => _guard(() => _working.search(query, language)));
  }
}

